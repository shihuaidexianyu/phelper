/// Read the software policy with one active-scheme lookup. Individual
/// settings are optional because Windows can hide/remove processor-class
/// settings on different CPUs or power-policy implementations. The active
/// scheme itself is the only hard requirement for a snapshot.
pub(crate) fn read_windows_ppm_state() -> Result<WindowsPpmState, PlatformError> {
    let scheme = active_scheme()?;
    let read_optional =
        |ac: bool, setting: &GUID| read_index(ac, &scheme, &SUB_PROCESSOR, setting).ok();
    let parse_percent = |v: Option<u32>| v.and_then(|v| u8::try_from(v).ok()).filter(|v| *v <= 100);
    let parse_boost = |v: Option<u32>| {
        v.and_then(|v| u8::try_from(v).ok())
            .and_then(|v| BoostPolicy::try_from(v).ok())
    };
    let values = |ac: bool| WindowsPpmValues {
        epp: parse_percent(read_optional(ac, &PERFEPP)),
        epp1: parse_percent(read_optional(ac, &PERFEPP1)),
        boost_policy: parse_boost(read_optional(ac, &PERFBOOSTMODE)),
        max_freq_mhz: read_optional(ac, &PROCFREQMAX),
        min_performance: parse_percent(read_optional(ac, &PROCTHROTTLEMIN)),
        max_performance: parse_percent(read_optional(ac, &PROCTHROTTLEMAX)),
    };
    Ok(WindowsPpmState {
        active_scheme_guid: guid_string(&scheme),
        active_scheme_name: known_scheme_name(&scheme).into(),
        configured_ac_mode: read_configured_mode(true).ok(),
        configured_dc_mode: read_configured_mode(false).ok(),
        effective_mode: effective_mode(),
        ac: values(true),
        dc: values(false),
    })
}

#[cfg(feature = "control")]
#[allow(dead_code)] // wired in W11 (ControlCoordinator's PpmBackend)
fn write_index(
    ac: bool,
    scheme: &GUID,
    subgroup: &GUID,
    setting: &GUID,
    value: u32,
) -> Result<(), PlatformError> {
    unsafe {
        // windows-0.62 signature lottery (verified against generated
        // bindings): scheme = raw *const GUID; subgroup/setting =
        // Option<*const GUID>; AC → WIN32_ERROR, DC → u32.
        let rc = if ac {
            PowerWriteACValueIndex(
                None,
                scheme as *const GUID,
                Some(subgroup as *const GUID),
                Some(setting as *const GUID),
                value,
            )
            .0
        } else {
            PowerWriteDCValueIndex(
                None,
                scheme as *const GUID,
                Some(subgroup as *const GUID),
                Some(setting as *const GUID),
                value,
            )
        };
        if rc != 0 {
            return Err(PlatformError::Os(format!(
                "PowerWrite{}ValueIndex failed (win32 {})",
                if ac { "AC" } else { "DC" },
                rc
            )));
        }
        Ok(())
    }
}

/// Re-apply the scheme whose value index was written so the change takes
/// effect (the powercfg /S pattern: PowerWrite*ValueIndex only touches the
/// store). Reusing the same GUID avoids committing a different scheme if
/// Windows changes the active scheme between the write and the commit.
#[cfg(feature = "control")]
#[allow(dead_code)] // wired in W11 (ControlCoordinator's PpmBackend)
fn commit_active_scheme(scheme: &GUID) -> Result<(), PlatformError> {
    unsafe {
        let rc = PowerSetActiveScheme(None, Some(scheme));
        if rc.0 != 0 {
            return Err(PlatformError::Os(format!(
                "PowerSetActiveScheme failed (win32 {})",
                rc.0
            )));
        }
        Ok(())
    }
}

/// PowrProf implementation of the domain `CpuPolicyBackend` port (M2 write
/// path). Stateless — every call re-resolves the ACTIVE scheme (the user
/// may switch schemes between commands; we always act on what is active).
#[cfg(feature = "control")]
#[allow(dead_code)] // constructed by the ControlCoordinator (W11)
pub(crate) struct PpmBackend;

#[cfg(feature = "control")]
impl phelper_domain::ports::CpuPolicyBackend for PpmBackend {
    fn read_epp(&self) -> Result<(u8, u8), PlatformError> {
        let r = read_epp()?;
        Ok((r.ac, r.dc))
    }

    fn read_epp1(&self) -> Result<(u8, u8), PlatformError> {
        let r = read_epp1()?;
        Ok((r.ac, r.dc))
    }

    fn read_max_freq_mhz(&self) -> Result<(u32, u32), PlatformError> {
        read_max_freq_mhz_acdc()
    }

    fn read_boost_policy(&self) -> Result<(BoostPolicy, BoostPolicy), PlatformError> {
        read_boost_policy()
    }

    fn read_min_performance(&self) -> Result<(u8, u8), PlatformError> {
        read_min_performance()
    }

    fn read_max_performance(&self) -> Result<(u8, u8), PlatformError> {
        read_max_performance()
    }

    fn write_epp(&self, ac: Option<u8>, dc: Option<u8>) -> Result<(), PlatformError> {
        let scheme = active_scheme()?;
        if let Some(v) = ac {
            write_index(true, &scheme, &SUB_PROCESSOR, &PERFEPP, v as u32)?;
        }
        if let Some(v) = dc {
            write_index(false, &scheme, &SUB_PROCESSOR, &PERFEPP, v as u32)?;
        }
        if ac.is_some() || dc.is_some() {
            commit_active_scheme(&scheme)?;
        }
        Ok(())
    }

    fn write_epp1(&self, ac: Option<u8>, dc: Option<u8>) -> Result<(), PlatformError> {
        let scheme = active_scheme()?;
        if let Some(v) = ac {
            write_index(true, &scheme, &SUB_PROCESSOR, &PERFEPP1, v as u32)?;
        }
        if let Some(v) = dc {
            write_index(false, &scheme, &SUB_PROCESSOR, &PERFEPP1, v as u32)?;
        }
        if ac.is_some() || dc.is_some() {
            commit_active_scheme(&scheme)?;
        }
        Ok(())
    }

    fn write_max_freq_mhz(&self, ac: Option<u32>, dc: Option<u32>) -> Result<(), PlatformError> {
        let scheme = active_scheme()?;
        if let Some(v) = ac {
            write_index(true, &scheme, &SUB_PROCESSOR, &PROCFREQMAX, v)?;
        }
        if let Some(v) = dc {
            write_index(false, &scheme, &SUB_PROCESSOR, &PROCFREQMAX, v)?;
        }
        if ac.is_some() || dc.is_some() {
            commit_active_scheme(&scheme)?;
        }
        Ok(())
    }

    fn write_boost_policy(
        &self,
        ac: Option<BoostPolicy>,
        dc: Option<BoostPolicy>,
    ) -> Result<(), PlatformError> {
        let scheme = active_scheme()?;
        if let Some(mode) = ac {
            write_index(
                true,
                &scheme,
                &SUB_PROCESSOR,
                &PERFBOOSTMODE,
                u8::from(mode) as u32,
            )?;
        }
        if let Some(mode) = dc {
            write_index(
                false,
                &scheme,
                &SUB_PROCESSOR,
                &PERFBOOSTMODE,
                u8::from(mode) as u32,
            )?;
        }
        if ac.is_some() || dc.is_some() {
            commit_active_scheme(&scheme)?;
        }
        Ok(())
    }

    fn write_min_performance(&self, ac: Option<u8>, dc: Option<u8>) -> Result<(), PlatformError> {
        let scheme = active_scheme()?;
        if let Some(v) = ac {
            write_index(true, &scheme, &SUB_PROCESSOR, &PROCTHROTTLEMIN, v as u32)?;
        }
        if let Some(v) = dc {
            write_index(false, &scheme, &SUB_PROCESSOR, &PROCTHROTTLEMIN, v as u32)?;
        }
        if ac.is_some() || dc.is_some() {
            commit_active_scheme(&scheme)?;
        }
        Ok(())
    }

    fn write_max_performance(&self, ac: Option<u8>, dc: Option<u8>) -> Result<(), PlatformError> {
        let scheme = active_scheme()?;
        if let Some(v) = ac {
            write_index(true, &scheme, &SUB_PROCESSOR, &PROCTHROTTLEMAX, v as u32)?;
        }
        if let Some(v) = dc {
            write_index(false, &scheme, &SUB_PROCESSOR, &PROCTHROTTLEMAX, v as u32)?;
        }
        if ac.is_some() || dc.is_some() {
            commit_active_scheme(&scheme)?;
        }
        Ok(())
    }

    fn read_windows_ppm_state(&self) -> Result<Option<WindowsPpmState>, PlatformError> {
        read_windows_ppm_state().map(Some)
    }
}

