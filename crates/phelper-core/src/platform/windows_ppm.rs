// Windows 11 user-configured power-mode overlay GUIDs. These APIs are not
// generated by windows-rs 0.62 yet, so the small PowrProf declarations are
// kept here. They are read-only in phelper; mode writes stay out of the
// product until Windows' voting/override semantics are modelled properly.
windows::core::link!(
    "powrprof.dll" "system"
    fn PowerGetUserConfiguredACPowerMode(power_mode_guid: *mut GUID) -> u32
);
windows::core::link!(
    "powrprof.dll" "system"
    fn PowerGetUserConfiguredDCPowerMode(power_mode_guid: *mut GUID) -> u32
);

const USER_MODE_BEST_EFFICIENCY: GUID = GUID::from_values(
    0x961c_c777,
    0x2547,
    0x4f9d,
    [0x81, 0x74, 0x7d, 0x86, 0x18, 0x1b, 0x8a, 0x7a],
);
const USER_MODE_BALANCED: GUID = GUID::zeroed();
const USER_MODE_BEST_PERFORMANCE: GUID = GUID::from_values(
    0xded5_74b5,
    0x45a0,
    0x4f42,
    [0x87, 0x37, 0x46, 0x34, 0x5c, 0x09, 0xc2, 0x38],
);

static EFFECTIVE_MODE: OnceLock<Mutex<Option<WindowsEffectivePowerMode>>> = OnceLock::new();
static EFFECTIVE_MODE_REGISTERED: OnceLock<bool> = OnceLock::new();

unsafe extern "system" fn effective_mode_callback(
    mode: EFFECTIVE_POWER_MODE,
    context: *const core::ffi::c_void,
) {
    if context.is_null() {
        return;
    }
    let Some(mode) = effective_mode_from_raw(mode.0) else {
        return;
    };
    // The context points at the process-lifetime OnceLock value below. It is
    // never freed, so callbacks that arrive after registration remain safe.
    let slot = unsafe { &*(context as *const Mutex<Option<WindowsEffectivePowerMode>>) };
    if let Ok(mut current) = slot.lock() {
        *current = Some(mode);
    }
}

fn effective_mode_from_raw(value: i32) -> Option<WindowsEffectivePowerMode> {
    Some(match value {
        0 => WindowsEffectivePowerMode::BatterySaver,
        1 => WindowsEffectivePowerMode::BetterBattery,
        2 => WindowsEffectivePowerMode::Balanced,
        3 => WindowsEffectivePowerMode::HighPerformance,
        4 => WindowsEffectivePowerMode::MaxPerformance,
        5 => WindowsEffectivePowerMode::GameMode,
        6 => WindowsEffectivePowerMode::MixedReality,
        _ => return None,
    })
}

fn effective_mode() -> Option<WindowsEffectivePowerMode> {
    let slot = EFFECTIVE_MODE.get_or_init(|| Mutex::new(None));
    let registered = *EFFECTIVE_MODE_REGISTERED.get_or_init(|| {
        let context =
            slot as *const Mutex<Option<WindowsEffectivePowerMode>> as *const core::ffi::c_void;
        let mut registration = std::ptr::null_mut();
        // V2 is preferred because it is the current API; V1 is the
        // compatibility fallback documented by PowrProf.
        let registered = unsafe {
            PowerRegisterForEffectivePowerModeNotifications(
                EFFECTIVE_POWER_MODE_V2,
                Some(effective_mode_callback),
                Some(context),
                &mut registration,
            )
            .is_ok()
        } || unsafe {
            PowerRegisterForEffectivePowerModeNotifications(
                EFFECTIVE_POWER_MODE_V1,
                Some(effective_mode_callback),
                Some(context),
                &mut registration,
            )
            .is_ok()
        };
        // The registration intentionally lives for the process lifetime. Its
        // callback writes only to the static lock; this avoids a race between
        // an asynchronous callback and a short-lived context during refresh.
        registered
    });
    if !registered {
        debug!("effective power-mode notification registration unavailable");
        return None;
    }
    // The contract says registration invokes the callback immediately, but
    // some Windows builds deliver it on a worker thread. Give that callback
    // a bounded opportunity to publish the initial value without turning
    // startup into a blocking probe.
    for _ in 0..3 {
        if let Some(mode) = slot.lock().ok().and_then(|current| *current) {
            return Some(mode);
        }
        std::thread::sleep(std::time::Duration::from_millis(1));
    }
    None
}

fn configured_mode_from_guid(guid: GUID) -> Option<WindowsConfiguredPowerMode> {
    if guid == USER_MODE_BEST_EFFICIENCY {
        Some(WindowsConfiguredPowerMode::BestEfficiency)
    } else if guid == USER_MODE_BALANCED {
        Some(WindowsConfiguredPowerMode::Balanced)
    } else if guid == USER_MODE_BEST_PERFORMANCE {
        Some(WindowsConfiguredPowerMode::BestPerformance)
    } else {
        None
    }
}

fn read_configured_mode(ac: bool) -> Result<WindowsConfiguredPowerMode, PlatformError> {
    let mut guid = GUID::zeroed();
    let rc = unsafe {
        if ac {
            PowerGetUserConfiguredACPowerMode(&mut guid)
        } else {
            PowerGetUserConfiguredDCPowerMode(&mut guid)
        }
    };
    if rc != 0 {
        return Err(PlatformError::Os(format!(
            "PowerGetUserConfigured{}PowerMode failed (win32 {rc})",
            if ac { "AC" } else { "DC" }
        )));
    }
    configured_mode_from_guid(guid).ok_or(PlatformError::Data(
        "unknown Windows user-configured power-mode GUID",
    ))
}

fn guid_string(guid: &GUID) -> String {
    format!(
        "{:08x}-{:04x}-{:04x}-{:02x}{:02x}-{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}",
        guid.data1,
        guid.data2,
        guid.data3,
        guid.data4[0],
        guid.data4[1],
        guid.data4[2],
        guid.data4[3],
        guid.data4[4],
        guid.data4[5],
        guid.data4[6],
        guid.data4[7]
    )
}

fn known_scheme_name(guid: &GUID) -> &'static str {
    match guid_string(guid).as_str() {
        "a1841308-3541-4fab-bc81-f71556f20b4a" => "Power saver",
        "381b4222-f694-41f0-9685-ff5bb260df2e" => "Balanced",
        "8c5e7fda-e8bf-4a96-9a85-a6e23a8c635c" => "High performance",
        _ => "Custom",
    }
}

/// EPP values in percent (0 = max performance, 100 = max efficiency),
/// split by power source as Windows stores them.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct EppReading {
    pub ac: u8,
    pub dc: u8,
}

fn active_scheme() -> Result<GUID, PlatformError> {
    unsafe {
        let mut scheme: *mut GUID = std::ptr::null_mut();
        let rc = PowerGetActiveScheme(None, &mut scheme);
        if rc.0 != 0 || scheme.is_null() {
            return Err(PlatformError::Os(format!(
                "PowerGetActiveScheme failed (win32 {})",
                rc.0
            )));
        }
        let guid = *scheme;
        // PowerGetActiveScheme allocates via LocalAlloc.
        let _ = LocalFree(Some(HLOCAL(scheme.cast())));
        Ok(guid)
    }
}

fn read_index(
    ac: bool,
    scheme: &GUID,
    subgroup: &GUID,
    setting: &GUID,
) -> Result<u32, PlatformError> {
    unsafe {
        let mut value: u32 = 0;
        // windows 0.62: AC variant returns WIN32_ERROR, DC variant u32.
        let rc = if ac {
            PowerReadACValueIndex(
                None,
                Some(scheme),
                Some(subgroup),
                Some(setting),
                &mut value,
            )
            .0
        } else {
            PowerReadDCValueIndex(
                None,
                Some(scheme),
                Some(subgroup),
                Some(setting),
                &mut value,
            )
        };
        if rc != 0 {
            return Err(PlatformError::Os(format!(
                "PowerRead{}ValueIndex failed (win32 {})",
                if ac { "AC" } else { "DC" },
                rc
            )));
        }
        Ok(value)
    }
}

/// Read current EPP from the active power scheme. Works unelevated (reads
/// are not privileged; only writes are).
pub(crate) fn read_epp() -> Result<EppReading, PlatformError> {
    let scheme = active_scheme()?;
    let ac = read_index(true, &scheme, &SUB_PROCESSOR, &PERFEPP)?;
    let dc = read_index(false, &scheme, &SUB_PROCESSOR, &PERFEPP)?;
    if ac > 100 || dc > 100 {
        return Err(PlatformError::Data("EPP out of 0-100 range"));
    }
    Ok(EppReading {
        ac: ac as u8,
        dc: dc as u8,
    })
}

/// Read the class-1 (E-core) EPP (PERFEPP1) from the active power scheme.
pub(crate) fn read_epp1() -> Result<EppReading, PlatformError> {
    let scheme = active_scheme()?;
    let ac = read_index(true, &scheme, &SUB_PROCESSOR, &PERFEPP1)?;
    let dc = read_index(false, &scheme, &SUB_PROCESSOR, &PERFEPP1)?;
    if ac > 100 || dc > 100 {
        return Err(PlatformError::Data("EPP1 out of 0-100 range"));
    }
    Ok(EppReading {
        ac: ac as u8,
        dc: dc as u8,
    })
}

/// Read the max-frequency ceiling on both rails (AC, DC).
pub(crate) fn read_max_freq_mhz_acdc() -> Result<(u32, u32), PlatformError> {
    let scheme = active_scheme()?;
    let ac = read_index(true, &scheme, &SUB_PROCESSOR, &PROCFREQMAX)?;
    let dc = read_index(false, &scheme, &SUB_PROCESSOR, &PROCFREQMAX)?;
    Ok((ac, dc))
}

/// Read PERFBOOSTMODE on both rails (AC, DC).
#[allow(dead_code)] // wired in W11 (PpmBackend reads)
pub(crate) fn read_boost_policy() -> Result<(BoostPolicy, BoostPolicy), PlatformError> {
    let scheme = active_scheme()?;
    let ac = read_index(true, &scheme, &SUB_PROCESSOR, &PERFBOOSTMODE)?;
    let dc = read_index(false, &scheme, &SUB_PROCESSOR, &PERFBOOSTMODE)?;
    let parse = |v: u32| {
        u8::try_from(v)
            .ok()
            .and_then(|b| BoostPolicy::try_from(b).ok())
            .ok_or(PlatformError::Data("unknown PERFBOOSTMODE value"))
    };
    Ok((parse(ac)?, parse(dc)?))
}

/// Read PROCTHROTTLEMIN on both rails (0..=100%).
pub(crate) fn read_min_performance() -> Result<(u8, u8), PlatformError> {
    let scheme = active_scheme()?;
    let ac = read_index(true, &scheme, &SUB_PROCESSOR, &PROCTHROTTLEMIN)?;
    let dc = read_index(false, &scheme, &SUB_PROCESSOR, &PROCTHROTTLEMIN)?;
    let parse = |v: u32| {
        u8::try_from(v)
            .ok()
            .filter(|v| *v <= 100)
            .ok_or(PlatformError::Data(
                "minimum processor state out of 0-100 range",
            ))
    };
    Ok((parse(ac)?, parse(dc)?))
}

