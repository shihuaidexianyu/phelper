    #[test]
    fn windows_mode_guid_mapping_is_explicit() {
        assert_eq!(
            configured_mode_from_guid(USER_MODE_BEST_EFFICIENCY),
            Some(WindowsConfiguredPowerMode::BestEfficiency)
        );
        assert_eq!(
            configured_mode_from_guid(USER_MODE_BALANCED),
            Some(WindowsConfiguredPowerMode::Balanced)
        );
        assert_eq!(
            configured_mode_from_guid(USER_MODE_BEST_PERFORMANCE),
            Some(WindowsConfiguredPowerMode::BestPerformance)
        );
        assert_eq!(configured_mode_from_guid(SUB_PROCESSOR), None);
    }

    #[test]
    fn effective_mode_mapping_is_fail_closed() {
        assert_eq!(
            effective_mode_from_raw(0),
            Some(WindowsEffectivePowerMode::BatterySaver)
        );
        assert_eq!(
            effective_mode_from_raw(6),
            Some(WindowsEffectivePowerMode::MixedReality)
        );
        assert_eq!(effective_mode_from_raw(7), None);
    }

    #[test]
    fn boost_policy_wire_roundtrip() {
        for v in 0u8..=6 {
            let p = BoostPolicy::try_from(v).unwrap();
            assert_eq!(u8::from(p), v);
        }
        assert!(BoostPolicy::try_from(7u8).is_err());
    }
